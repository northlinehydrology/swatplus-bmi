"""A hash of the swatplus-bmi sources an exchange executable is built from.

build.sh writes it into the executable (``bmi_build_module.f90``), SWAT+
sends it in its catalog, and the Python wrapper compares it with the hash of
its own copy of the same files, so an executable built from other sources
(an older checkout, a changed patch) is refused instead of run. The files
are the ones that go into the exchange build: build.sh, patches/, fortran/
and the tools build.sh runs on the SWAT+ sources.

    python tools/source_hash.py <folder with build.sh>               # print the hash
    python tools/source_hash.py <folder with build.sh> --fortran <out.f90>
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

PARTS = ("build.sh", "patches", "fortran", "tools/carried_locals.py", "tools/gen_serializer.py",
         "tools/source_hash.py")


def source_hash(root: str | Path) -> str:
    root = Path(root)
    h = hashlib.sha256()
    for part in PARTS:
        p = root / part
        files = [p] if p.is_file() else sorted(f for f in p.rglob("*") if f.is_file())
        for f in files:
            if "__pycache__" in f.parts or f.suffix == ".pyc":
                continue
            rel = f.relative_to(root).as_posix()
            data = f.read_bytes().replace(b"\r\n", b"\n")
            h.update(rel.encode() + b"\0" + str(len(data)).encode() + b"\0" + data)
    return h.hexdigest()[:32]


def fortran(digest: str) -> str:
    return ("      module bmi_build_module\n"
            "!!    generated by swatplus-bmi's tools/source_hash.py: the hash of the\n"
            "!!    swatplus-bmi sources this executable was built from\n"
            "      implicit none\n"
            f'      character(len=32), parameter :: swx_build = "{digest}"\n'
            "      end module bmi_build_module\n")


if __name__ == "__main__":
    digest = source_hash(sys.argv[1])
    if len(sys.argv) == 4 and sys.argv[2] == "--fortran":
        Path(sys.argv[3]).write_text(fortran(digest))
    else:
        print(digest)
