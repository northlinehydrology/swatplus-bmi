"""Move the saved locals that carry state into a module, so they can be saved.

Most of SWAT+'s implicitly saved locals (locals with initializers) carry
nothing between calls, but a few do, such as a "header written" flag. A
local can't be reached from outside its procedure, so the serializer can't
save it where it is. This tool moves each local listed in a release's
``patches/<tag>/carried-locals.toml`` into a generated module,
``bmi_locals_module.f90``, and has the procedure use it under its old name:

    logical :: write_hdr = .true.     ->   use bmi_locals_module, only : write_hdr => swx_l1
                                           (and in bmi_locals_module: logical :: swx_l1 = .true.)

A module variable keeps its value between calls just as a saved local does,
so SWAT+ behaves exactly as before. The list comes from
tests/test_saved_locals.py: a local belongs on it if resetting it on every
call changes SWAT+'s output.

    python tools/carried_locals.py <carried-locals.toml> <SWAT+ src/ to edit in place>
"""

from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from state_inventory import parse_decl, split_top, strip_comment  # noqa: E402


def load(path: Path):
    return tomllib.loads(path.read_text()).get("local", [])


def move(src: Path, entries):
    module = ["      module bmi_locals_module", "",
              "!!    GENERATED by tools/carried_locals.py. Saved locals of SWAT+ procedures",
              "!!    that carry state between calls, moved here so bmi_state_module can save",
              "!!    them. Each keeps its declaration and starting value.", "",
              "      implicit none", ""]
    for k, e in enumerate(entries, 1):
        f = src / e["file"]
        lines = f.read_text().splitlines()
        start = next((i for i, l in enumerate(lines)
                      if re.match(rf"^\s*(?:\w+\s+)*(subroutine|function)\s+{e['procedure']}\b",
                                  strip_comment(l), re.I)), None)
        if start is None:
            raise SystemExit(f"{e['file']}: no procedure {e['procedure']}")
        decl = None
        for i in range(start + 1, len(lines)):
            text = strip_comment(lines[i])
            if re.match(r"^\s*end\s*(subroutine|function)\b", text, re.I):
                break
            if "::" in text and re.search(rf"::\s*{e['name']}\b", text, re.I):
                decl = i
                break
        if decl is None:
            raise SystemExit(f"{e['file']}: no declaration of {e['name']} in {e['procedure']}")
        text = strip_comment(lines[decl])
        if text.rstrip().endswith("&"):
            raise SystemExit(f"{e['file']}: the declaration of {e['name']} continues; not handled")
        names = split_top(text.split("::", 1)[1])
        if len(names) != 1:
            raise SystemExit(f"{e['file']}: {e['name']} shares its declaration; not handled")
        head = text.split("::", 1)[0].strip()
        if parse_decl(text) is None:
            raise SystemExit(f"{e['file']}: can't read {text.strip()}")
        init = names[0].split("=", 1)[1].strip()
        new = f"swx_l{k}"
        module.append(f"!!    {e['file']}, {e['procedure']}: {e['name']}")
        module.append(f"      {head} :: {new} = {init}")
        indent = re.match(r"\s*", lines[start + 1]).group(0) or "      "
        del lines[decl]
        lines.insert(start + 1, f"{indent}use bmi_locals_module, only : {e['name']} => {new}"
                                "   !! swatplus-bmi: a saved local that carries state")
        f.write_text("\n".join(lines) + "\n")
    module += ["", "      end module bmi_locals_module", ""]
    (src / "bmi_locals_module.f90").write_text("\n".join(module))
    return len(entries)


def main():
    entries = load(Path(sys.argv[1]))
    n = move(Path(sys.argv[2]), entries)
    print(f"moved {n} carried locals into bmi_locals_module.f90")


if __name__ == "__main__":
    main()
